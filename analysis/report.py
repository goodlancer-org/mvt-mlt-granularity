def escape(value):
    if value is None:
        return "---"
    if isinstance(value, float):
        return f"{value:.3f}" if math.isfinite(value) else "---"
    if isinstance(value, int):
        return f"{value:,}".replace(",", r"\,")
    replacements = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&",
                    "#": r"\#", "$": r"\$", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(c,c) for c in str(value))


def write_table(con, name, query):
    cursor = con.execute(query)
    columns = [c[0] for c in cursor.description]
    rows = cursor.fetchall()
    column_spec=''.join('l' if any(isinstance(row[i],str) for row in rows) else 'r' for i in range(len(columns)))
    display = {d['id']:d['display_name'] for d in registry()}
    display.update(standard='Std',dense4='D4',dense16='D16')
    headings = {'dataset_id':'Dataset','dataset_name':'Dataset','variant':'Variant',
                'tile_count':'Tiles','mlt_raw_saving_pct':r'$S_{\rm raw}$ (\%)',
                'mlt_after_gzip_saving_pct':r'$S_{\rm gz}$ (\%)',
                'g_raw':r'$G_{\rm raw}$ (pp)','g_gz':r'$G_{\rm gz}$ (pp)',
                'vertex_bin':'Vertices/tile','avg_mvt_raw_kib':'MVT KiB',
                'values_per_stream':'Values/stream','r_struct':r'$R_{\rm struct}$',
                'stream_header_share':'Header share','payload_bytes_per_value':'B/value',
                'sourceFormat':'Format','file_mib':'MiB','layers':'Layers','features':'Features',
                'vertices':'Vertices','fields':'Fields','mvt_raw':'MVT raw','mlt_raw':'MLT raw',
                'mvt_gzip6':'MVT gz','mlt_gzip6':'MLT gz'}
    headings.update(stored_saving_pct='Stored (\\%)',gzip6_saving_pct='Gzip-6 (\\%)',delta_pp='Change (pp)',
                    g_gzip9='Gzip-9 (pp)',g_brotli11='Brotli-11 (pp)',g_zstd19='Zstd-19 (pp)')
    headings.update(Columns='Columns', Mixed='Mixed', Values='Values', ToString='To string',
                    ToStringPct='To string (\\%)')
    headings.update(checked_tiles='Compared', mismatches='Differing', errors='Decode errors',
                    passed='Strict equality')
    lines = ["% Generated by manage.py report; requires booktabs and longtable.",
             r"\begingroup\small\setlength{\tabcolsep}{3pt}",
             r"\begin{longtable}{" + column_spec + "}", r"\toprule",
             " & ".join(headings.get(c,escape(c)) for c in columns)+r" \\", r"\midrule"]
    lines += [" & ".join(escape(display.get(v,v) if isinstance(v,str) else v) for v in row)+r" \\" for row in rows]
    lines += [r"\bottomrule",r"\end{longtable}",r"\endgroup"]
    (TABLES / f"{name}.tex").write_text("\n".join(lines)+"\n",encoding="utf-8")
    with (DATA / f"{name}.csv").open("w",encoding="utf-8",newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(columns)
        writer.writerows(rows)


def save_figure(fig, name):
    fig.savefig(FIGURES / f"{name}.pdf",bbox_inches="tight",metadata={"CreationDate":None,"ModDate":None})
    fig.savefig(FIGURES / f"{name}.png",dpi=600,bbox_inches="tight")


