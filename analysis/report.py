def paper_zoom_chart(con):
    """Article-sized multi-panel plot, ordered by measured Standard stream length."""
    import matplotlib.pyplot as plt
    from .paper_tables import PAPER_NAMES

    datasets = con.execute("SELECT dataset_name FROM stream_summary WHERE variant='standard' ORDER BY values_per_stream,dataset_name").fetchall()
    fig, axes = plt.subplots(2, len(datasets), figsize=(7, 3.5), squeeze=False)
    display = {d['id']: d['display_name'] for d in registry()}
    styles = [('standard', 'Standard', '#2166ac', '-', 'o'),
              ('dense4', 'Dense-4', '#b2182b', '--', 's'),
              ('dense16', 'Dense-16', '#1b7837', ':', '^')]
    for column, (dataset,) in enumerate(datasets):
        for variant, label, colour, line, marker in styles:
            rows = con.execute('SELECT logical_z,mlt_raw_saving_pct,mlt_after_gzip_saving_pct FROM logical_zoom_summary WHERE dataset_name=? AND variant=? ORDER BY logical_z', (dataset, variant)).fetchall()
            for row in range(2):
                axes[row, column].plot([r[0] for r in rows], [r[row+1] for r in rows],
                    color=colour, linestyle=line, marker=marker, markersize=2,
                    linewidth=.9, label=label, markerfacecolor='none')
        axes[0, column].set_title(PAPER_NAMES.get(dataset, display[dataset]), fontsize=8)
        axes[1, column].set_xlabel('Logical zoom', fontsize=8)
        for row in range(2):
            ax = axes[row, column]
            ax.tick_params(labelsize=8, pad=2)
            ax.set_xticks([4, 8, 12])
            ax.grid(color='#dddddd', linewidth=.4)
            ax.set_axisbelow(True)
    axes[0, 0].set_ylabel(r'$S_{\mathrm{raw}}$ (%)', fontsize=8)
    axes[1, 0].set_ylabel(r'$S_{\mathrm{gz}}$ (%)', fontsize=8)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='lower center', ncol=3, frameon=False, fontsize=8)
    fig.subplots_adjust(left=.07, right=.995, top=.92, bottom=.19, wspace=.45, hspace=.35)
    save_figure(fig, 'analysis_zoom_aligned')
    plt.close(fig)


def paper_sample_fragment(panel_records):
    """Keep panel labels, actual addresses and attribution in sync with rendering."""
    from .paper_tables import PAPER_NAMES

    records = {p['dataset_id']: p for p in panel_records}
    display = {d['id']: d['display_name'] for d in registry()}
    ids = [key for key in PAPER_NAMES if key in records]
    ids += sorted(set(records) - set(ids))
    lines = ['% Generated by manage.py report; do not edit.',
             r'\setlength{\tabcolsep}{2pt}', r'\begin{tabular}{ccc}']
    for start in range(0, len(ids), 3):
        group = ids[start:start+3]
        images, labels = [], []
        for index, dataset in enumerate(group, start):
            p = records[dataset]
            images.append(r'\includegraphics[width=0.31\textwidth]{figures/analysis_sample_' + dataset + '.pdf}')
            labels.append(r'\shortstack{(' + chr(97+index) + ') ' + escape(PAPER_NAMES.get(dataset, display[dataset]))
                          + r'\\\scriptsize ' + f"$z={p['z']}$, $x={p['x']}$, $y={p['y']}$" + '}')
        lines += [' & '.join(images + ['']*(3-len(group))) + r' \\',
                  ' & '.join(labels + ['']*(3-len(group))) + r' \\[4pt]']
    lines += [r'\end{tabular}', r'\par\smallskip',
              r'\includegraphics[width=0.85\textwidth]{figures/analysis_sample_legend.pdf}']
    attributions = '; '.join(escape(records[key]['attribution']).replace('©', r'\copyright{}') for key in ids)
    lines += [r'\caption{Samples decoded from Standard MVT tiles with a common style based on retained tile-layer names.',
              'Each panel selects the tile with the most vertices at the highest stored zoom; addresses are shown below the panels.',
              'Colours denote layer names and do not reclassify their contents. Sources: ' + attributions + '.}']
    (FIGURES/'analysis_sample_panels.tex').write_text('\n'.join(lines)+'\n', encoding='utf-8')


def sample_panels():
    """Render deterministic real MVT content; retain semantic layer names for styling."""
    import matplotlib.pyplot as plt
    from matplotlib.collections import LineCollection, PolyCollection
    import mapbox_vector_tile
    from . import output_analysis_core as core
    style = json.loads((Path(__file__).parent/"style.json").read_text())
    panel_records=[]
    for d in registry():
        path=ROOT/"app/data/output"/f"{d['id']}_standard_mvt.pmtiles"
        with closing(sqlite3.connect(f"file:{DATA/'tile_stats.sqlite'}?mode=ro",uri=True)) as db:
            row=db.execute("""SELECT t.z,t.x,t.y,t.content_offset,t.stored_bytes
                FROM tiles t JOIN archives a ON a.id=t.archive_id JOIN maps m ON m.id=a.map_id
                JOIN tile_content_stats c ON c.map_id=m.id AND c.z=t.z AND c.x=t.x AND c.y=t.y
                WHERE m.dataset_name=? AND m.variant='standard' AND a.format='MVT'
                AND t.z=a.max_zoom ORDER BY c.vertex_count DESC,t.x,t.y LIMIT 1""",(d['id'],)).fetchone()
        if row is None:
            raise RuntimeError(f"No sample tile for {d['id']}")
        z,x,y,offset,length=row
        header=core.read_pmtiles_header(path)
        with path.open('rb') as handle:
            raw=core._decompress(core._read_section(handle,header.tile_data_offset+offset,length),header.tile_compression,str(path))
        decoded=mapbox_vector_tile.decode(raw)
        fig,ax=plt.subplots(figsize=(2.5,2.5))
        order=['land_use','terrain','hydrography','buildings','infrastructure','transportation','boundaries','places']
        for layer_name,layer in sorted(decoded.items(),key=lambda item: order.index(item[0]) if item[0] in order else 4):
            color=style.get(layer_name,style['default'])
            extent=layer.get('extent',4096)
            lines=[];polygons=[];points=[]
            def collect(g):
                kind=g['type'];coords=g.get('coordinates',[])
                if kind=='Point':points.append(coords)
                elif kind=='MultiPoint':points.extend(coords)
                elif kind=='LineString':lines.append(coords)
                elif kind=='MultiLineString':lines.extend(coords)
                elif kind=='Polygon':polygons.append(coords)
                elif kind=='MultiPolygon':polygons.extend(coords)
                elif kind=='GeometryCollection':
                    for child in g['geometries']:collect(child)
            for feature in layer['features']:
                if feature.get('geometry'):collect(feature['geometry'])
            # Compound paths preserve interior rings rather than filling lakes/islands.
            from matplotlib.path import Path as MplPath
            from matplotlib.patches import PathPatch
            for rings in polygons:
                vertices=[];codes=[]
                for ring in rings:
                    if len(ring)<3:continue
                    vertices.extend(ring);codes.extend([MplPath.MOVETO]+[MplPath.LINETO]*(len(ring)-2)+[MplPath.CLOSEPOLY])
                if vertices:ax.add_patch(PathPatch(MplPath(vertices,codes),
                    facecolor='none' if layer_name=='boundaries' else color,edgecolor=color,lw=.2,
                    alpha=.2 if layer_name=='places' else 1))
            if lines:ax.add_collection(LineCollection(lines,colors=color,linewidths=.25))
            if points:ax.scatter([p[0] for p in points],[p[1] for p in points],s=.5,c=color)
        ax.set_xlim(0,extent);ax.set_ylim(0,extent);ax.set_aspect('equal');ax.axis('off')
        save_figure(fig,"analysis_sample_"+d['id']);plt.close(fig)
        panel_records.append(dict(dataset_id=d['id'],variant='standard',z=z,x=x,y=y,
            attribution=d.get('attribution',d['display_name']),
            selection='maximum vertices at maximum stored zoom; x/y tie break'))
    (DATA/'sample_panels.json').write_text(json.dumps(panel_records,indent=2),encoding='utf-8')
    from matplotlib.patches import Patch
    fig,ax=plt.subplots(figsize=(7,.6));ax.axis('off')
    ax.legend(handles=[Patch(facecolor=color,label=('Other' if key=='default' else key.replace('_',' ').capitalize())) for key,color in style.items()],
              loc='center',ncol=5,frameon=False,fontsize=8)
    save_figure(fig,'analysis_sample_legend');plt.close(fig)
    paper_sample_fragment(panel_records)


