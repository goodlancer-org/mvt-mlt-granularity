"""Row fragments for the article's existing table layouts, from measured SQLite data.

Run independently with ``python -m analysis.paper_tables`` or through ``report``.
The article owns captions, labels and column headings; this module owns data rows.
"""
from contextlib import closing
from pathlib import Path
import sqlite3

from .pipeline import DATA, ROOT, registry

VARIANTS = ('standard', 'dense4', 'dense16')
VARIANT_TEX = dict(zip(VARIANTS, (r'\VStd', r'\VDfour', r'\VDsixteen')))
# Manuscript order and abbreviated labels; unknown registry entries follow these.
PAPER_NAMES = {
    'natural_earth_vector': 'Natural Earth',
    'pdok_netherlands_infrostructure': 'PDOK BGT',
    'usfws_luisiana_wetlands_geopackage': 'USFWS',
    'swisstopo_mountains_vector': 'swisstopo',
    'louisiana-260912': 'OSM',
}


def number(value, decimals=0):
    if value is None:
        return '---'
    return f'{value:,.{decimals}f}'.replace(',', '{,}')


def signed(value):
    return '---' if value is None else f'${value:+.1f}$'


def write_paper_tables(con, tiles, target, datasets):
    """Write fragments using open results/tile connections, without modifying either DB."""
    target = Path(target)
    target.mkdir(parents=True, exist_ok=True)

    def records(query):
        cursor = con.execute(query)
        names = [column[0] for column in cursor.description]
        return [dict(zip(names, row)) for row in cursor]

    def keyed(query, *keys):
        return {tuple(row[key] for key in keys): row for row in records(query)}

    def emit(name, rows):
        text = '% Generated by analysis.paper_tables from SQLite; do not edit.\n'
        text += '\n'.join(row if isinstance(row, str) else ' & '.join(row) + r' \\' for row in rows)
        # Keep the closing alignment rule inside the input: LaTeX's \input
        # bookkeeping between a row terminator and \bottomrule breaks \noalign.
        if name.endswith('_rows'):
            text += '\n' + r'\bottomrule'
        (target / f'paper_{name}.tex').write_text(text + '\n', encoding='utf-8')

    display = {d['id']: PAPER_NAMES.get(d['id'], d['display_name']) for d in datasets}
    ids = sorted(display, key=lambda key: (list(PAPER_NAMES).index(key) if key in PAPER_NAMES else len(PAPER_NAMES), key))
    raw = keyed('SELECT * FROM raw_structure', 'dataset_id')
    normalized = keyed('SELECT * FROM normalized_structure', 'dataset_id')
    area = keyed('SELECT * FROM study_area', 'dataset_id')
    layers = keyed("SELECT dataset_name,COUNT(DISTINCT layer_name) AS n FROM layer_compression WHERE variant='standard' GROUP BY dataset_name", 'dataset_name')
    zoom = keyed("SELECT dataset_name,MIN(logical_z) AS lo,MAX(logical_z) AS hi FROM logical_zoom_summary WHERE variant='standard' GROUP BY dataset_name", 'dataset_name')
    source_rows, normalized_rows = [], []
    for dataset in ids:
        source, gpkg = raw[dataset,], normalized[dataset,]
        bounds_area = area[dataset,]['area_km2']
        area_tex = (number(bounds_area / 1e6, 1) + r'\,M') if bounds_area is not None and bounds_area >= 1e6 else number(bounds_area)
        z = zoom[dataset,]
        source_rows.append([display[dataset], number(source['fileBytes'] / 1e6),
                            *[number(source[k]) for k in ('layers', 'features', 'fields')],
                            area_tex, number(layers[dataset,]['n']), f"{z['lo']}--{z['hi']}"])
        normalized_rows.append([display[dataset], number(gpkg['fileBytes'] / 1048576, 1),
                                *[number(gpkg[k]) for k in ('layers', 'features', 'vertices', 'fields')]])
    emit('sources_rows', source_rows)
    emit('normalized_rows', normalized_rows)

    summary = keyed('SELECT * FROM variant_summary', 'dataset_name', 'variant')
    gains = keyed('SELECT * FROM granularity_gain', 'dataset_id', 'variant')
    main_rows = []
    for dataset in ids:
        variants = [summary[dataset, v] for v in VARIANTS]
        gain = gains[dataset, 'dense16']
        main_rows.append([display[dataset], *[number(v['tile_count']) for v in variants],
                          *[number(v['mlt_raw_saving_pct'], 1) for v in variants], signed(gain['g_raw']),
                          *[number(v['mlt_after_gzip_saving_pct'], 1) for v in variants], signed(gain['g_gz'])])
    emit('compression_rows', main_rows)

    bin_rows = []
    for row in records('SELECT * FROM vertex_summary ORDER BY avg_vertices'):
        label = row['vertex_bin']
        if label.endswith('+'):
            label = r'$\geq$' + number(int(label[:-1]))
        else:
            label = '--'.join(number(int(v)) for v in label.split('-'))
        bin_rows.append([label, number(row['tile_count']), number(row['avg_mvt_raw_kib'], 1),
                         *[('$' + number(row[k], 1) + '$') for k in ('mlt_raw_saving_pct', 'mlt_after_gzip_saving_pct')]])
    emit('vertex_bins_rows', bin_rows)

    streams = keyed('SELECT * FROM stream_summary', 'dataset_name', 'variant')
    stream_rows = []
    for dataset in sorted(ids, key=lambda d: (streams[d, 'standard']['values_per_stream'], d)):
        variants = [streams[dataset, v] for v in VARIANTS]
        stream_rows.append([display[dataset], *[number(v['values_per_stream']) for v in variants],
                            *[number(100 * v['r_struct'], 2) for v in variants],
                            number(variants[0]['payload_bytes_per_value'], 3), number(variants[2]['payload_bytes_per_value'], 3),
                            number(gains[dataset, 'dense16']['g_raw'], 1)])
    emit('streams_rows', stream_rows)

    bpv = keyed('SELECT * FROM bytes_per_vertex', 'dataset_id', 'variant')
    bpv_rows = []
    for dataset in ids:
        if bpv_rows:
            bpv_rows.append(r'\addlinespace')
        for i, variant in enumerate(VARIANTS):
            row = bpv[dataset, variant]
            bpv_rows.append([display[dataset] if i == 0 else '', VARIANT_TEX[variant],
                             *[number(row[k], 1) for k in ('mvt_raw', 'mvt_gzip6', 'mlt_raw', 'mlt_gzip6')]])
    emit('bytes_per_vertex_rows', bpv_rows)

    # Read actual encoded extents and logical offsets, rather than restating constants.
    extents = {v: (lo, hi) for v, lo, hi in tiles.execute('SELECT variant,MIN(extent),MAX(extent) FROM tile_layers JOIN maps ON maps.id=map_id GROUP BY variant')}
    offsets = {v: (lo, hi) for v, lo, hi in tiles.execute('SELECT variant,MIN(logical_zoom-z),MAX(logical_zoom-z) FROM tiles JOIN archives ON archives.id=archive_id JOIN maps ON maps.id=archives.map_id GROUP BY variant')}
    factors = {v: (lo, hi) for v, lo, hi in con.execute('SELECT variant,MIN(density_factor),MAX(density_factor) FROM variant_summary GROUP BY variant')}
    variant_rows = []
    for variant in VARIANTS:
        for measured in (extents[variant], offsets[variant], factors[variant]):
            if measured[0] is None or measured[0] != measured[1]:
                raise ValueError(f'Inconsistent variant parameters: {variant}: {measured}')
        extent, offset, factor = extents[variant][0], offsets[variant][0], factors[variant][0]
        variant_rows.append([VARIANT_TEX[variant], number(offset), number(extent), number(factor), f'${factor}\\times$'])
    emit('variants_rows', variant_rows)

    total = sum(row['tile_count'] for row in summary.values())
    ne = sum(row['tile_count'] for (dataset, _), row in summary.items() if dataset == 'natural_earth_vector')
    emit('numbers', [r'\providecommand{\PaperTilesTotal}{' + number(total) + '}',
                     r'\providecommand{\PaperNaturalEarthTileShare}{' + number(100 * ne / total) + '}'])


def main():
    with closing(sqlite3.connect((DATA / 'results.sqlite').as_uri() + '?mode=ro', uri=True)) as con, \
         closing(sqlite3.connect((DATA / 'tile_stats.sqlite').as_uri() + '?mode=ro', uri=True)) as tiles:
        write_paper_tables(con, tiles, ROOT / 'outputs/tables', registry())


if __name__ == '__main__':
    main()
