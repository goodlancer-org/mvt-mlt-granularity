"""Generate every primary numerical article table, figure and numerical claim."""
from __future__ import annotations
import json
from pathlib import Path
import sqlite3
from contextlib import closing
from .extended import EXT,VARIANTS,FORMATS
from .pipeline import ROOT,DATA,registry
from .paper_tables import PAPER_NAMES,number

LABELS={'standard':'Std','aggregated4':'A4','aggregated16':'A16','dense4':'D4','dense16':'D16'}
FORMAT_LABELS={'mvt':'MVT','mltv1':'MLT v1','mltv2':'MLT v2'}


def report():
    tables=ROOT/'paper/latex/tables';figures=ROOT/'paper/latex/figures'
    tables.mkdir(parents=True,exist_ok=True);figures.mkdir(parents=True,exist_ok=True)
    with closing(sqlite3.connect(EXT/'results.sqlite')) as con:
        con.row_factory=sqlite3.Row
        def rows(sql,params=()):return [dict(r) for r in con.execute(sql,params)]
        def emit(name,lines,bottom=True):
            text='% Generated by analysis.extended_report from measured extended results; do not edit.\n'
            text+='\n'.join(line if isinstance(line,str) else ' & '.join(line)+r' \\' for line in lines)
            if bottom:text+='\n'+r'\bottomrule'
            (tables/('extended_'+name+'.tex')).write_text(text+'\n',encoding='utf-8')
        ids=[d for d in PAPER_NAMES if d in {r['dataset'] for r in rows('SELECT DISTINCT dataset FROM archive_summary')}]
        inventory_tables(tables,con,ids)
        summary={(r['dataset'],r['variant'],r['format']):r for r in rows('SELECT * FROM archive_summary')}
        savings={(r['dataset'],r['variant'],r['format']):r for r in rows('SELECT * FROM savings')}
        streams={(r['dataset'],r['variant'],r['format']):r for r in rows('SELECT * FROM stream_summary')}
        bpv={(r['dataset'],r['variant'],r['format']):r for r in rows('SELECT * FROM bytes_per_vertex')}
        decomp={(r['dataset'],r['factor'],r['format'],r['compression_state']):r for r in rows('SELECT * FROM decomposition')}
        variants=[]
        for v,offset in VARIANTS.items():
            variants.append([{'standard':'Standard','aggregated4':'Aggregated-4','aggregated16':'Aggregated-16','dense4':'Dense-4','dense16':'Dense-16'}[v],
                str(4**offset),str(4096*2**offset),str(offset),
                'Exact Standard multiset' if v.startswith('aggregated') else ('Regenerated' if v.startswith('dense') else 'Conventional baseline')])
        emit('variants_rows',variants)
        compression=[];stream_rows=[];bpv_rows=[]
        for d in ids:
            for i,v in enumerate(VARIANTS):
                prefix=[PAPER_NAMES[d] if i==0 else '',LABELS[v]]
                compression.append(prefix+[number(summary[d,v,'mvt']['tiles'])]+[
                    number(savings[d,v,f][k],1) for k in ('raw_saving_pct','gzip_saving_pct') for f in FORMATS[1:]])
                stream_rows.append(prefix+[number(streams[d,v,f][k]*(100 if k=='structural_share' else 1),
                    2 if k=='structural_share' else (3 if k=='payload_bytes_per_value' else 0))
                    for k in ('values_per_stream','structural_share','payload_bytes_per_value') for f in FORMATS[1:]])
                bpv_rows.append(prefix+[number(bpv[d,v,f][k],2) for f in FORMATS for k in ('raw_bytes_per_vertex','gzip_bytes_per_vertex')])
        emit('compression_rows',compression);emit('streams_rows',stream_rows);emit('bpv_rows',bpv_rows)
        decomposition=[]
        for d in ids:
            for factor in (4,16):
                for comp in ('raw','gzip6'):
                    decomposition.append([PAPER_NAMES[d] if factor==4 and comp=='raw' else '',str(factor),'raw' if comp=='raw' else 'gzip',
                        *[number(decomp[d,factor,f,comp][k],1) for f in FORMATS[1:]
                            for k in ('aggregation_pct','regeneration_pct','total_pct')]])
        emit('decomposition_rows',decomposition)
        content=[]
        for d in ids:
            for factor in (4,16):
                r=rows('SELECT * FROM content_differences WHERE dataset=? AND factor=?',(d,factor))[0]
                content.append([PAPER_NAMES[d] if factor==4 else '',str(factor),
                    *[number(r[k]/1000,1) for k in ('aggregated_features','dense_features','aggregated_vertices','dense_vertices',
                        'aggregated_source_features_zoom_sum','dense_source_features_zoom_sum','aggregated_repeated_vertices','dense_repeated_vertices')]])
        emit('content_rows',content)
        unique=[]
        for d in ids:
            for v in VARIANTS:
                records=rows('SELECT SUM(feature_instances) n,SUM(unique_source_features) u,SUM(repeated_instances) r FROM content_summary WHERE dataset=? AND variant=?',(d,v))[0]
                unique.append([PAPER_NAMES[d],LABELS[v],*[number(records[k]) for k in ('n','u','r')]])
        emit('identity_rows',unique)
        bins=[]
        for r in rows("SELECT CASE WHEN variant='standard' THEN 'Standard' WHEN variant LIKE 'aggregated%' THEN 'Aggregated' ELSE 'Dense' END regime,format,vertex_bin,SUM(tiles) tiles,100.*(1.-SUM(mlt_raw_bytes)*1./SUM(mvt_raw_bytes)) raw_saving_pct,100.*(1.-SUM(mlt_gzip_bytes)*1./SUM(mvt_gzip_bytes)) gzip_saving_pct FROM vertex_bins GROUP BY 1,2,3 ORDER BY 1,2,MIN(CASE vertex_bin WHEN '<100' THEN 0 WHEN '100--999' THEN 1 WHEN '1,000--9,999' THEN 2 WHEN '10,000--99,999' THEN 3 ELSE 4 END)"):
            label=r['vertex_bin'].replace('<',r'$<$').replace('+',r'$+$')
            bins.append([r['regime'],FORMAT_LABELS[r['format']],label,number(r['tiles']),number(r['raw_saving_pct'],1),number(r['gzip_saving_pct'],1)])
        emit('bins_rows',bins)
        # Article statements are generated from the same integer-byte decomposition.
        numbers=[]
        claims={}
        for f,suffix in [('mltv1','One'),('mltv2','Two')]:
            for comp,cs in [('raw','Raw'),('gzip6','Gzip')]:
                data=[decomp[d,16,f,comp] for d in ids]
                for metric,ms in [('aggregation_pct','Aggregation'),('regeneration_pct','Regeneration'),('total_pct','Total')]:
                    values=[r[metric] for r in data]
                    for stat,func in [('Min',min),('Max',max)]:
                        key=suffix+cs+ms+stat
                        value=func(values);numbers.append(r'\providecommand{\Ext'+key+'}{'+f'{value:.1f}'+'}')
                        claims[key]=value
                key=suffix+cs+'AggregationPositive';value=sum(r['aggregation_pct']>0 for r in data)
                numbers.append(r'\providecommand{\Ext'+key+'}{'+str(value)+'}');claims[key]=value
        total=sum(r['tiles'] for r in summary.values() if r['format']=='mvt')
        checked=sum(r['checked_addresses'] for r in rows('SELECT * FROM validation_summary'))
        differences=sum(r['differing_addresses'] for r in rows('SELECT * FROM validation_summary'))
        blocks=sum(r['blocks'] for r in rows('SELECT * FROM aggregation_validation'))
        for key,value in [('Tiles',total),('CheckedAddresses',checked),('RoundtripDifferences',differences),('AggregateBlocks',blocks)]:
            numbers.append(r'\providecommand{\Ext'+key+'}{'+number(value)+'}');claims[key]=value
        emit('numbers',numbers,bottom=False)
        checks={
            'all five datasets, five variants and three formats':len(summary)==75 and len(ids)==5,
            'all aggregation blocks preserve the typed feature multiset':len(rows('SELECT * FROM aggregation_validation'))==10 and all(r['passed'] for r in rows('SELECT * FROM aggregation_validation')),
            'all MLT round trips match the normalized Rust MVT importer':differences==0 and len(rows('SELECT * FROM validation_summary'))==50,
            'integer byte decomposition is exactly additive':all(r['aggregation_reduction_bytes']+r['regeneration_reduction_bytes']==r['total_reduction_bytes'] for r in rows('SELECT * FROM decomposition_zoom')),
            'aggregation preserves feature and stored vertex counts in every matched block':all(r['standard_features']==r['aggregated_features'] and r['standard_vertices']==r['aggregated_vertices'] for r in rows('SELECT * FROM content_differences')),
        }
        provenance=[json.loads(p.read_text()) for p in (EXT/'manifests').glob('*.json')]
        builds={r['manifest']['inputs']['build']['binary_sha256'] for r in provenance}
        checks['one pinned Rust binary encodes both versions in every primary variant']=len(provenance)==25 and len(builds)==1
        checks['every MVT address has both independently verified MLT versions']=checked==2*total
        physical=rows('SELECT * FROM physical_archives')
        checks['all 75 physical archives contain the measured addresses and verified payload bytes']=(
            len(physical)==75 and sum(r['verified_addresses'] for r in physical)==3*total and
            all(r['address_payloads_match_measurements'] for r in physical))
        claims['checks']=checks
        claims['queries']={'abstract_ranges':"SELECT format,compression_state,MIN(aggregation_pct),MAX(aggregation_pct),MIN(total_pct),MAX(total_pct) FROM decomposition WHERE factor=16 GROUP BY 1,2",
            'exact_decomposition':"SELECT * FROM decomposition_zoom WHERE aggregation_reduction_bytes+regeneration_reduction_bytes!=total_reduction_bytes",
            'roundtrip':"SELECT * FROM validation_summary",'content':'SELECT * FROM content_differences'}
        (DATA/'extended_claims.json').write_text(json.dumps(claims,indent=2)+'\n',encoding='utf-8')
        (DATA/'extended_checks.md').write_text('# Extended experiment validation\n\n'+
            '\n'.join(f'- {"PASS" if ok else "FAIL"}: {label}' for label,ok in checks.items())+
            '\n\nNative round trips compare against the Rust MVT importer, after its column-type unification. They allow integer-width changes and polygon winding, as in the official MapLibre CLI verifier. They are not a proof of strict typed protobuf equality. Aggregation uses a separate exact typed multiset test. See extended_attribute_summary.csv and extended_validation_summary.csv for importer normalization and geometry-count diagnostics.\n',encoding='utf-8')
        zoom_chart(con,figures,ids)
        # Rebuild curated cartographic illustrations from the regenerated Standard MVT.
        from .map_figures import generate
        generate(ROOT/'app/data/output',figures)
        if not all(checks.values()):raise RuntimeError('Extended validation failed: '+', '.join(k for k,v in checks.items() if not v))
    print('Generated extended article tables, figures, claims and validation checks',flush=True)


def inventory_tables(target,results,ids):
    """Regenerate source/normalization tables from hash-verified unchanged inventories."""
    from .release import sha256
    inventories={}
    for stage,name,key in [('raw','source_stats','source'),('normalized','normalized_stats','normalized')]:
        with closing(sqlite3.connect(DATA/(name+'.sqlite'))) as db:
            db.row_factory=sqlite3.Row
            value=db.execute("SELECT value FROM meta WHERE key='inputs_json'").fetchone()
            known={r.get('sha256') for r in json.loads(value[0])} if value else set()
            for d in registry():
                if sha256(ROOT/d[key]) not in known:
                    raise ValueError(f'Rebuild {name}: source hash absent from measured inventory: {d["id"]}')
            query='''SELECT d.dataset_id,m.fileBytes,COUNT(l.layerName) layers,
              CASE WHEN COUNT(l.featureInstances)=COUNT(l.layerName) THEN SUM(l.featureInstances) END features,
              CASE WHEN COUNT(l.vertexCount)=COUNT(l.layerName) THEN SUM(l.vertexCount) END vertices,
              SUM(l.fieldCount) fields FROM dataset_files d JOIN maps m ON m.mapName=d.map_name
              LEFT JOIN layers l ON l.mapName=m.mapName GROUP BY d.dataset_id,m.fileBytes'''
            records=[dict(r) for r in db.execute(query)]
            inventories[stage]={r['dataset_id']:r for r in records}
            if stage=='normalized':
                area={r['dataset_id']:dict(r) for r in db.execute('SELECT * FROM study_area')}
    source_rows=[];normalized_rows=[]
    from .extended import connect
    with closing(connect()) as tiles:
        layers={r[0]:r[1] for r in tiles.execute("SELECT dataset,COUNT(DISTINCT layer) FROM content WHERE variant='standard' GROUP BY dataset").fetchall()}
    for d in ids:
        raw=inventories['raw'][d];norm=inventories['normalized'][d];a=area[d]['area_km2']
        area_tex=(number(a/1e6,1)+r'\,M') if a is not None and a>=1e6 else number(a)
        zoom=results.execute("SELECT MIN(logical_z),MAX(logical_z) FROM zoom_summary WHERE dataset=? AND variant='standard'",(d,)).fetchone()
        source_rows.append([PAPER_NAMES[d],number(raw['fileBytes']/1e6),*[number(raw[k]) for k in ('layers','features','fields')],area_tex,number(layers[d]),str(zoom[0])+'--'+str(zoom[1])])
        normalized_rows.append([PAPER_NAMES[d],number(norm['fileBytes']/1048576,1),*[number(norm[k]) for k in ('layers','features','vertices','fields')]])
    for name,values in [('paper_sources_rows',source_rows),('paper_normalized_rows',normalized_rows)]:
        text='% Generated by analysis.extended_report from hash-verified inventories and extended tiles.\n'
        text+='\n'.join(' & '.join(r)+r' \\' for r in values)+'\n'+r'\bottomrule'+'\n'
        (target/(name+'.tex')).write_text(text,encoding='utf-8')


def zoom_chart(con,figures,ids):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.ticker import MaxNLocator
    colours={'standard':'#777777','aggregated4':'#4393c3','aggregated16':'#2166ac','dense4':'#f4a582','dense16':'#b2182b'}
    fig,axes=plt.subplots(2,len(ids),figsize=(7.2,3.8),squeeze=False)
    for col,d in enumerate(ids):
        for v in VARIANTS:
            for f in FORMATS[1:]:
                rows=con.execute('''SELECT l.logical_z,100.*(1.-l.raw_bytes*1./m.raw_bytes),100.*(1.-l.gzip_bytes*1./m.gzip_bytes)
                    FROM zoom_summary l JOIN zoom_summary m ON m.dataset=l.dataset AND m.variant=l.variant AND m.logical_z=l.logical_z AND m.format='mvt'
                    WHERE l.dataset=? AND l.variant=? AND l.format=? ORDER BY l.logical_z''',(d,v,f)).fetchall()
                for row in range(2):
                    axes[row,col].plot([r[0] for r in rows],[r[row+1] for r in rows],color=colours[v],
                        linestyle='-' if f=='mltv1' else '--',linewidth=.85,label=LABELS[v]+' '+FORMAT_LABELS[f])
        axes[0,col].set_title(PAPER_NAMES[d],fontsize=8)
        axes[1,col].set_xlabel('Logical zoom',fontsize=8)
        for row in range(2):
            axes[row,col].tick_params(labelsize=7);axes[row,col].grid(alpha=.25,linewidth=.4)
            axes[row,col].xaxis.set_major_locator(MaxNLocator(integer=True,nbins=3))
    axes[0,0].set_ylabel('Raw saving (%)',fontsize=8);axes[1,0].set_ylabel('Gzip saving (%)',fontsize=8)
    handles,labels=axes[0,0].get_legend_handles_labels()
    fig.legend(handles,labels,loc='lower center',ncol=5,fontsize=7,frameon=False)
    fig.subplots_adjust(left=.08,right=.995,top=.93,bottom=.23,wspace=.45,hspace=.35)
    for ext in ('pdf','png'):fig.savefig(figures/('analysis_zoom_aligned.'+ext),dpi=300)
    plt.close(fig)

if __name__=='__main__':report()
